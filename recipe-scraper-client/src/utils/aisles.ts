// Kurze Keywords (≤ 3 Zeichen, z. B. "ei", "öl", "tee") nur als Wort oder Wortende
// (Komposita: "Olivenöl", "Hühnerei"), sonst trifft "ei" in "Weizen".
const matches = (name: string, kw: string) =>
    kw.length <= 3
        ? name.split(/[^\p{L}]+/u).some((w) => w.endsWith(kw))
        : name.includes(kw);

export const aisleOf = (ing: {
    name: string;
    aisle?: string | null;
}): AisleId => {
    if (ing.aisle) return ing.aisle as AisleId;
    const name = ing.name.toLowerCase();
    let best: AisleId = 'other';
    let bestLen = 0;
    for (const a of AISLES) {
        for (const kw of a.keywords as readonly string[]) {
            if (kw.length > bestLen && matches(name, kw)) {
                best = a.id;
                bestLen = kw.length;
            }
        }
    }
    return best;
};
